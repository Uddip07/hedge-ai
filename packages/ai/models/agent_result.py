"""
AgentResult Model for AI Core Framework.

Encapsulates analytical output generated by an AI research agent.
"""

from dataclasses import dataclass, field
from typing import Any

from packages.domain.ai.reasoning import Evidence, ReasoningTrace
from packages.domain.enums.ai import AgentType
from packages.domain.enums.research import RecommendationType
from packages.domain.value_objects.metrics.scores import ConfidenceScore, RecommendationScore


@dataclass(frozen=True)
class AgentResult:
    """
    Output analysis result produced by a specialized AI research agent.

    Attributes:
        agent_type (AgentType): Specialized agent role.
        recommendation (RecommendationType): Directional trade recommendation.
        score (RecommendationScore): Recommendation score [-1.0, 1.0].
        confidence (ConfidenceScore): Confidence score [0, 1].
        reasoning (str): Textual justification summary.
        evidence (list[Evidence]): List of gathered evidence items.
        reasoning_trace (ReasoningTrace | None): Step-by-step chain-of-thought trace.
        execution_time_ms (float): Processing latency in milliseconds.
        risks (list[str]): Identified risk factors.
        assumptions (list[str]): Identified baseline assumptions.
        unknowns (list[str]): Identified missing or uncertain data points.
        reasoning_steps (list[str]): Explicit step-by-step reasoning steps.
    """

    agent_type: AgentType
    recommendation: RecommendationType
    score: RecommendationScore
    confidence: ConfidenceScore
    reasoning: str
    evidence: list[Evidence] = field(default_factory=list)
    reasoning_trace: ReasoningTrace | None = None
    execution_time_ms: float = 0.0
    risks: list[str] = field(default_factory=list)
    assumptions: list[str] = field(default_factory=list)
    unknowns: list[str] = field(default_factory=list)
    reasoning_steps: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        """Serialize AgentResult to dictionary."""
        return {
            "agent_type": self.agent_type.value,
            "recommendation": self.recommendation.value,
            "score": str(self.score.value),
            "confidence": str(self.confidence.value),
            "reasoning": self.reasoning,
            "evidence": [e.to_dict() for e in self.evidence],
            "reasoning_trace": self.reasoning_trace.to_dict() if self.reasoning_trace else None,
            "execution_time_ms": self.execution_time_ms,
            "risks": list(self.risks),
            "assumptions": list(self.assumptions),
            "unknowns": list(self.unknowns),
            "reasoning_steps": list(self.reasoning_steps),
        }
